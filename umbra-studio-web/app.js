function preferredLanguage() {
  const langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
  return langs.some((lang) => lang.toLowerCase().startsWith("zh")) ? "zh" : "en";
}

function el(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text) node.textContent = text;
  return node;
}

function renderSections(parent, sections) {
  sections.forEach((section) => {
    const wrap = el("section", "section");
    wrap.appendChild(el("h2", "", section.title));
    if (section.body) {
      section.body.forEach((paragraph) => wrap.appendChild(el("p", "", paragraph)));
    }
    if (section.list) {
      const list = el("ul");
      section.list.forEach((item) => list.appendChild(el("li", "", item)));
      wrap.appendChild(list);
    }
    parent.appendChild(wrap);
  });
}

function render() {
  const langKey = preferredLanguage();
  const copy = pages[langKey];
  const pageKey = document.body.dataset.page || "home";
  const page = copy[pageKey];
  document.documentElement.lang = langKey === "zh" ? "zh-CN" : "en";
  document.title = `${page.kicker} - ${copy.appName}`;

  const root = document.getElementById("app");
  const shell = el("div", "shell");
  const topbar = el("header", "topbar");
  const brand = el("a", "brand");
  brand.href = "index.html";
  const icon = document.createElement("img");
  icon.src = "icon.png";
  icon.alt = copy.appName;
  const brandText = el("div");
  brandText.appendChild(el("strong", "", copy.appName));
  brandText.appendChild(el("span", "", copy.label));
  brand.appendChild(icon);
  brand.appendChild(brandText);

  const nav = el("nav", "nav");
  [
    ["index.html", copy.nav.home],
    ["privacy.html", copy.nav.privacy],
    ["terms.html", copy.nav.terms],
    ["support.html", copy.nav.support]
  ].forEach(([href, label]) => {
    const link = document.createElement("a");
    link.href = href;
    link.textContent = label;
    nav.appendChild(link);
  });

  topbar.appendChild(brand);
  topbar.appendChild(nav);
  shell.appendChild(topbar);

  const article = el("main", "document");
  article.appendChild(el("p", "kicker", page.kicker));
  article.appendChild(el("h1", "", page.title));
  article.appendChild(el("p", "lede", page.lede));
  const meta = el("div", "meta");
  meta.appendChild(el("span", "", copy.updated));
  meta.appendChild(el("span", "", copy.effective));
  article.appendChild(meta);

  if (page.cards) {
    const cards = el("div", "cards");
    page.cards.forEach(([title, desc, href]) => {
      const card = el("a", "card");
      card.href = href;
      card.appendChild(el("strong", "", title));
      card.appendChild(el("span", "", desc));
      cards.appendChild(card);
    });
    article.appendChild(cards);
  }

  renderSections(article, page.sections);
  article.appendChild(el("p", "footer", `${copy.appName} / ${page.kicker}`));
  shell.appendChild(article);
  root.replaceChildren(shell);
}

render();
